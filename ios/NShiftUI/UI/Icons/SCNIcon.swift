struct SCNIcon: View {
    let name: SCNIconName
    let size: CGFloat
    let color: Color?

    init(
        _ name: SCNIconName,
        size: CGFloat = 24,
        color: Color? = nil
    ) {
        self.name = name
        self.size = size
        self.color = color
    }

    var body: some View {
        Group {
            if let color {
                Image(name.rawValue)
                    .renderingMode(.template)
                    .resizable()
                    .foregroundStyle(color)
            } else {
                Image(name.rawValue)
                    .renderingMode(.template)
                    .resizable()
            }
        }
            .aspectRatio(contentMode: .fit)
            .frame(
                width: size,
                height: size
            )
    }


}

